"""Build the Cloudflare Worker from editable sources; Python only."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parent
ui=(ROOT/'dashboard.html').read_text(encoding='utf-8-sig')
for begin,end,source in [
 ('<!-- BEGIN PRODUCER VIEW -->','<!-- END PRODUCER VIEW -->','producer-view.html'),
 ('// BEGIN PRODUCER UI LOGIC','// END PRODUCER UI LOGIC','producer-view.js'),
 ('<!-- BEGIN CONTENT VIEW -->','<!-- END CONTENT VIEW -->','content-view.html'),
 ('// BEGIN CONTENT UI LOGIC','// END CONTENT UI LOGIC','content-view.js'),
 ('/* BEGIN CONTENT UI STYLES */','/* END CONTENT UI STYLES */','content-view.css'),
]:
 a=ui.index(begin)+len(begin);b=ui.index(end,a)
 ui=ui[:a]+'\n'+(ROOT/source).read_text(encoding='utf-8')+'\n'+ui[b:]
(ROOT/'dashboard.html').write_text(ui,encoding='utf-8')
s='// Generated by build_ui.py. Edit the component sources.\nconst HTML = '+json.dumps(ui,ensure_ascii=True)+';\n'
schema=json.loads((ROOT/'store-schema.json').read_text())
s+=(ROOT/'sheets-store.js').read_text().replace('__STORE_SCHEMA__',json.dumps(schema,separators=(',',':')))+'\n'
s+='const SOURCE_REGISTRY = '+json.dumps(json.loads((ROOT/'producer-sources.json').read_text()),separators=(',',':'),ensure_ascii=True)+';\n'
for name in ['producer-policy.js','sheets-sync.js','content-ledger.js','meta-worker.js','worker-runtime.js']:s+=(ROOT/name).read_text(encoding='utf-8')+'\n'
(ROOT/'worker.js').write_text(s,encoding='utf-8')
print('Worker rebuilt: Google Sheets storage, UI, producer policy and collectors.')
