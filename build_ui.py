"""Build the Cloudflare Worker from editable sources; Python only."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parent
ui=(ROOT/'dashboard.html').read_text(encoding='utf-8-sig')
for begin,end,source in [
 ('<!-- BEGIN INFRA VIEW -->','<!-- END INFRA VIEW -->','infra-view.html'),
 ('// BEGIN INFRA UI','// END INFRA UI','infra-view.js'),
 ('/* BEGIN INFRA STYLES */','/* END INFRA STYLES */','infra-view.css'),
 ('<!-- BEGIN PRODUCER VIEW -->','<!-- END PRODUCER VIEW -->','producer-view.html'),
 ('// BEGIN PRODUCER UI LOGIC','// END PRODUCER UI LOGIC','producer-view.js'),
 ('<!-- BEGIN CONTENT VIEW -->','<!-- END CONTENT VIEW -->','content-view.html'),
 ('// BEGIN CONTENT UI LOGIC','// END CONTENT UI LOGIC','content-view.js'),
 ('// BEGIN POST EXTRAS UI','// END POST EXTRAS UI','content-extras-ui.js'),
 ('/* BEGIN CONTENT UI STYLES */','/* END CONTENT UI STYLES */','content-view.css'),
]:
 a=ui.index(begin)+len(begin);b=ui.index(end,a)
 component=(ROOT/source).read_text(encoding='utf-8')
 if source=='producer-view.html':
  begin2='<!-- BEGIN SNAPCHAT VIEW -->';end2='<!-- END SNAPCHAT VIEW -->'
  a2=component.index(begin2)+len(begin2);b2=component.index(end2,a2)
  updated=component[:a2]+'\n'+(ROOT/'snapchat-view.html').read_text(encoding='utf-8')+'\n'+component[b2:]
  if component!=updated:
   component=updated
   (ROOT/source).write_text(component,encoding='utf-8',newline='\n')
 if source=='producer-view.js': component+='\n'+(ROOT/'snapchat-view.js').read_text(encoding='utf-8')
 if source=='infra-view.html': component=component.replace(' <div id="infra-summary"',(ROOT/'infra-config.html').read_text(encoding='utf-8')+'\n <div id="infra-summary"')
 if source=='infra-view.js': component+='\n'+(ROOT/'infra-config-ui.js').read_text(encoding='utf-8')
 if source=='infra-view.js': component+='\n'+(ROOT/'b2-reference-view.js').read_text(encoding='utf-8')
 ui=ui[:a]+'\n'+component+'\n'+ui[b:]
(ROOT/'dashboard.html').write_text(ui,encoding='utf-8',newline='\n')
s='// Generated by build_ui.py. Edit the component sources.\nconst HTML = '+json.dumps(ui,ensure_ascii=True)+';\n'
schema=json.loads((ROOT/'store-schema.json').read_text())
s+=(ROOT/'sheets-store.js').read_text().replace('__STORE_SCHEMA__',json.dumps(schema,separators=(',',':')))+'\n'
s+='const CFG_INVENTORY = '+json.dumps(json.loads((ROOT/'infra-config.json').read_text(encoding='utf-8')),ensure_ascii=True)+';\n'
s+=(ROOT/'infra-config-api.js').read_text(encoding='utf-8')+'\n'
s+='const SOURCE_REGISTRY = '+json.dumps(json.loads((ROOT/'producer-sources.json').read_text()),separators=(',',':'),ensure_ascii=True)+';\n'
for name in ['producer-policy.js','sheets-sync.js','content-ledger.js','content-extras.js','meta-worker.js','scanner-bridge.js','scanner-automation.js','source-observations.js','b2-references.js','infra-desk.js','cleanup-worker.js','snapchat-worker.js','worker-runtime.js']:s+=(ROOT/name).read_text(encoding='utf-8')+'\n'
(ROOT/'worker.js').write_text(s,encoding='utf-8',newline='\n')
print('Worker rebuilt: Google Sheets storage, UI, producer policy and collectors.')
